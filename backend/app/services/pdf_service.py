class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that dynamically counts total pages and draws
    consistent running headers (on pages > 1) and running footers
    with 'Page X of Y' on all pages.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_and_footer(num_pages)
            super().showPage()
        super().save()

    def draw_header_and_footer(self, total_pages: int):
        self.saveState()

        # Running header on subsequent pages (pages > 1)
        if self._pageNumber > 1:
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(colors.HexColor("#4F46E5"))  # Indigo 600
            self.drawString(40, 755, "MEETMIND AI")

            self.setFont("Helvetica", 8)
            self.setFillColor(colors.HexColor("#64748B"))  # Slate 500
            self.drawString(108, 755, "•  Meeting-to-Action Executive Intelligence Report")

            self.setStrokeColor(colors.HexColor("#E2E8F0"))  # Slate 200
            self.setLineWidth(0.75)
            self.line(40, 747, 612 - 40, 747)

        # Running footer on all pages
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.75)
        self.line(40, 42, 612 - 40, 42)

        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        self.drawString(40, 30, "Generated by MeetMind AI • Verified Action Items & Executive Intelligence")

        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(612 - 40, 30, page_str)

        self.restoreState()


