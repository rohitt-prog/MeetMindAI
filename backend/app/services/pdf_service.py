    def generate_meeting_pdf(
        self,
        analysis: MeetingAnalysisResponse,
        title: Optional[str] = None,
        transcript: Optional[str] = None,
        meeting_id: Optional[str] = None,
        created_at: Optional[str] = None,
        updated_at: Optional[str] = None,
        answers_history: Optional[List[Dict[str, Any]]] = None,
    ) -> bytes:
        """
        Compiles the full meeting analysis, action items, ambiguity log, and transcript
        into a multi-page PDF document and returns the raw PDF bytes.
        """
        buffer = io.BytesIO()

        # Target printable width: 612 (letter width) - 80 (margins) = 532 pt
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            leftMargin=40,
            rightMargin=40,
            topMargin=48,
            bottomMargin=52,
        )

        styles = self._build_styles()
        story = []

        raw_title = title.strip() if title and title.strip() else "Meeting Action & Intelligence Report"
        display_title = sanitize_plain_text(raw_title)

        # =========================================================================
        # 1. Header & MeetMind AI Branding Banner
        # =========================================================================
        brand_left = [
            Paragraph("MEETMIND AI", styles["BrandTitle"]),
            Spacer(1, 1),
            Paragraph("AI-Powered Meeting-to-Action Executive Intelligence", styles["BrandSubtitle"]),
        ]
        brand_right = [
            Paragraph("<b>EXECUTIVE REPORT</b>", styles["BrandTag"]),
        ]
        brand_header_table = Table([[brand_left, brand_right]], colWidths=[380, 152])
        brand_header_table.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING", (0, 0), (-1, -1), 0),
            ("RIGHTPADDING", (0, 0), (-1, -1), 0),
            ("TOPPADDING", (0, 0), (-1, -1), 0),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
        ]))
        story.append(brand_header_table)
        story.append(Spacer(1, 4))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#4F46E5"), spaceAfter=8))

        # Meeting Title (XML-escaped for Paragraph)
        title_p = Paragraph(safe_paragraph_text(display_title), styles["ReportTitle"])
        story.append(title_p)
        story.append(Spacer(1, 4))

        # =========================================================================
        # 2. Executive Metadata Summary Grid
        # =========================================================================
        doc_created = self._format_date(created_at)
        effective_meeting_id = meeting_id or analysis.meeting_id or "Session Workspace (Unsaved)"

        # Collect open follow-ups from analysis.open_follow_ups plus deferred action items
        open_follow_ups = list(analysis.open_follow_ups) if analysis.open_follow_ups else []
        for a in analysis.action_items:
            if (a.status or "").lower().startswith("deferred"):
                item_desc = f"{a.task} (deferred to future meeting)"
                if not any(a.task.lower() in fu.lower() for fu in open_follow_ups):
                    open_follow_ups.append(item_desc)

        unresolved_clarifs = [c for c in analysis.clarifications if not c.resolved]
        resolved_clarifs = [c for c in analysis.clarifications if c.resolved]

        unresolved_count = len(unresolved_clarifs)
        follow_up_count = len(open_follow_ups)
        total_action_items = len(analysis.action_items)
        assigned_count = sum(1 for a in analysis.action_items if a.owner and a.owner.strip())
        decisions_count = len(analysis.decisions)
        topics_count = len(analysis.discussion_points)

        if unresolved_count > 0 and follow_up_count > 0:
            status_text = f"<font color='#B45309'><b>{unresolved_count} Clarification(s) | {follow_up_count} Follow-up(s)</b></font>"
        elif unresolved_count > 0:
            status_text = f"<font color='#B45309'><b>{unresolved_count} Clarification(s) Required</b></font>"
        elif follow_up_count > 0:
            status_text = f"<font color='#4F46E5'><b>0 Clarifications | {follow_up_count} Open Follow-up(s)</b></font>"
        else:
            if resolved_clarifs:
                status_text = "<font color='#047857'><b>Resolved (No Outstanding Issues)</b></font>"
            else:
                status_text = "<font color='#047857'><b>Verified &amp; Clear (No Outstanding Issues)</b></font>"

        meta_data = [
            [
                Paragraph("<b>Report Date:</b>", styles["MetaLabel"]),
                Paragraph(safe_paragraph_text(doc_created), styles["MetaValue"]),
                Paragraph("<b>Meeting ID:</b>", styles["MetaLabel"]),
                Paragraph(f"<code>{safe_paragraph_text(effective_meeting_id)}</code>", styles["MetaValue"]),
            ],
            [
                Paragraph("<b>Deliverables:</b>", styles["MetaLabel"]),
                Paragraph(f"<b>{total_action_items}</b> tasks ({assigned_count} assigned)", styles["MetaValue"]),
                Paragraph("<b>Decisions:</b>", styles["MetaLabel"]),
                Paragraph(f"<b>{decisions_count}</b> confirmed", styles["MetaValue"]),
            ],
            [
                Paragraph("<b>Status:</b>", styles["MetaLabel"]),
                Paragraph(status_text, styles["MetaValue"]),
                Paragraph("<b>Key Topics:</b>", styles["MetaLabel"]),
                Paragraph(f"<b>{topics_count}</b> topics covered", styles["MetaValue"]),
            ],
        ]

        meta_table = Table(meta_data, colWidths=[90, 176, 95, 171])
        meta_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ("BOX", (0, 0), (-1, -1), 0.75, colors.HexColor("#E2E8F0")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#F1F5F9")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))

        story.append(meta_table)
        story.append(Spacer(1, 8))
        story.append(HRFlowable(width="100%", thickness=0.75, color=colors.HexColor("#E2E8F0"), spaceAfter=8))

        # =========================================================================
        # 3. Executive Summary
        # =========================================================================
        story.append(Paragraph("1. Executive Summary", styles["SectionHeading"]))

        summary_text = analysis.summary.strip() if analysis.summary and analysis.summary.strip() else "No summary available."
        summary_p = Paragraph(safe_paragraph_text(summary_text), styles["ExecutiveSummary"])

        summary_card = Table([[summary_p]], colWidths=[532])
        summary_card.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ("BOX", (0, 0), (-1, -1), 0.75, colors.HexColor("#E2E8F0")),
            ("LINELEFT", (0, 0), (0, -1), 3.5, colors.HexColor("#4F46E5")),  # Indigo accent bar
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("LEFTPADDING", (0, 0), (-1, -1), 12),
            ("RIGHTPADDING", (0, 0), (-1, -1), 12),
        ]))
        story.append(summary_card)
        story.append(Spacer(1, 8))

        # =========================================================================
        # 4. Key Discussion Topics & Confirmed Decisions
        # =========================================================================
        story.append(Paragraph("2. Key Discussion Topics", styles["SectionHeading"]))
        if analysis.discussion_points:
            for dp in analysis.discussion_points:
                point_html = f"<font color='#4F46E5'>&bull;</font> &nbsp; {safe_paragraph_text(dp)}"
                story.append(Paragraph(point_html, styles["BulletPoint"]))
        else:
            story.append(Paragraph("No discussion topics recorded.", styles["EmptyNotice"]))

        story.append(Spacer(1, 6))

        story.append(Paragraph("3. Confirmed Decisions", styles["SectionHeading"]))
        if analysis.decisions:
            for dec in analysis.decisions:
                dec_html = f"<font color='#059669'><b>[CONFIRMED]</b></font> &nbsp; {safe_paragraph_text(dec)}"
                story.append(Paragraph(dec_html, styles["DecisionPoint"]))
        else:
            story.append(Paragraph("No explicit decisions finalized during this meeting.", styles["EmptyNotice"]))

        story.append(Spacer(1, 8))

        # =========================================================================
        # 5. Action Items Table
        # =========================================================================
        story.append(Paragraph("4. Assigned Action Items & Deliverables", styles["SectionHeading"]))

        if analysis.action_items:
            # Table columns sum to 532 pt: Task (232 pt), Owner (100 pt), Deadline (110 pt), Status (90 pt)
            action_table_data = [
                [
                    Paragraph("Task Deliverable", styles["TableHeader"]),
                    Paragraph("Assigned Owner", styles["TableHeader"]),
                    Paragraph("Target Deadline", styles["TableHeader"]),
                    Paragraph("Delivery Status", styles["TableHeader"]),
                ]
            ]

            for idx, item in enumerate(analysis.action_items):
                task_p = Paragraph(safe_paragraph_text(item.task), styles["TableCell"])
                is_deferred = (item.status or "").lower().startswith("deferred")
                has_owner_clarif = any(
                    c.related_action_item_id == item.id and c.category == "ownership" and not c.resolved
                    for c in analysis.clarifications
                )
                has_deadline_clarif = any(
                    c.related_action_item_id == item.id and c.category == "deadline" and not c.resolved
                    for c in analysis.clarifications
                )
                has_any_clarif = any(
                    c.related_action_item_id == item.id and not c.resolved
                    for c in analysis.clarifications
                )

                # Owner format
                if item.owner and item.owner.strip():
                    owner_p = Paragraph(f"<b>{safe_paragraph_text(item.owner)}</b>", styles["TableCellOwner"])
                elif is_deferred:
                    owner_p = Paragraph("<font color='#4F46E5'>Deferred to next meeting</font>", styles["TableCell"])
                elif has_owner_clarif:
                    owner_p = Paragraph("<font color='#B45309'><b>Unassigned</b><br/><font size='7'><i>(Clarification required)</i></font></font>", styles["TableCell"])
                else:
                    owner_p = Paragraph("<font color='#D97706'>Unassigned</font>", styles["TableCellMuted"])

                # Deadline format
                if item.deadline and item.deadline.strip():
                    if has_deadline_clarif:
                        deadline_p = Paragraph(f"<b>{safe_paragraph_text(item.deadline)}</b><br/><font color='#B45309' size='7'><i>(Clarification required)</i></font>", styles["TableCell"])
                    else:
                        deadline_p = Paragraph(safe_paragraph_text(item.deadline), styles["TableCell"])
                elif is_deferred:
                    deadline_p = Paragraph("<font color='#4F46E5'>Deferred</font>", styles["TableCellMuted"])
                elif has_deadline_clarif:
                    deadline_p = Paragraph("<font color='#B45309'><b>Unspecified</b><br/><font size='7'><i>(Clarification required)</i></font></font>", styles["TableCell"])
                else:
                    deadline_p = Paragraph("<font color='#94A3B8'>None specified</font>", styles["TableCellMuted"])

                # Status format
                status_raw = (item.status or "pending").strip().replace("_", " ").title()
                if is_deferred:
                    status_p = Paragraph("<font color='#4F46E5'><b>Deferred</b></font>", styles["TableCell"])
                elif status_raw.lower() in ("completed", "done", "resolved"):
                    status_p = Paragraph(f"<font color='#047857'><b>{safe_paragraph_text(status_raw)}</b></font>", styles["TableCell"])
                elif has_any_clarif:
                    status_p = Paragraph("<font color='#B45309'><b>Needs Clarification</b></font>", styles["TableCell"])
                elif status_raw.lower() in ("in progress", "in_progress"):
                    status_p = Paragraph(f"<font color='#2563EB'><b>{safe_paragraph_text(status_raw)}</b></font>", styles["TableCell"])
                else:
                    status_p = Paragraph(f"<font color='#475569'>{safe_paragraph_text(status_raw)}</font>", styles["TableCell"])

                action_table_data.append([task_p, owner_p, deadline_p, status_p])

            action_table = Table(action_table_data, colWidths=[232, 100, 110, 90], repeatRows=1)

            table_style = [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0F172A")),  # Slate 900
                ("BOX", (0, 0), (-1, -1), 0.75, colors.HexColor("#CBD5E1")),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                ("LEFTPADDING", (0, 0), (-1, -1), 6),
                ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]

            # Alternate row background colors
            for r_idx in range(1, len(action_table_data)):
                bg_col = colors.white if r_idx % 2 != 0 else colors.HexColor("#F8FAFC")
                table_style.append(("BACKGROUND", (0, r_idx), (-1, r_idx), bg_col))

            action_table.setStyle(TableStyle(table_style))
            story.append(action_table)
        else:
            story.append(Paragraph("No action items or deliverables were identified.", styles["EmptyNotice"]))

        story.append(Spacer(1, 8))

        # =========================================================================
        # 6. Ambiguity Detection & Clarification Audit
        # =========================================================================
        story.append(Paragraph("5. Ambiguity Detection & Clarification Audit", styles["SectionHeading"]))

        has_clarifications = bool(analysis.clarifications)
        has_follow_ups = bool(open_follow_ups)

        # 6.1 Render Clarification Cards (if any)
        if has_clarifications:
            answers_map = {}
            if answers_history:
                for ans in answers_history:
                    cid = ans.get("clarification_id")
                    if cid and "answer" in ans:
                        answers_map[cid] = ans["answer"]

            for c_idx, c_item in enumerate(analysis.clarifications):
                cat_badge = c_item.category.upper().replace("_", " ")
                status_label = "RESOLVED" if c_item.resolved else "CLARIFICATION REQUIRED"
                status_color = "#047857" if c_item.resolved else "#B45309"
                bg_box_color = colors.HexColor("#F0FDF4") if c_item.resolved else colors.HexColor("#FFFBEB")
                border_color = colors.HexColor("#BBF7D0") if c_item.resolved else colors.HexColor("#FDE68A")

                lines = []
                badge_html = f"<b>[{cat_badge}]</b>  &bull;  <font color='{status_color}'><b>{status_label}</b></font>"
                lines.append(Paragraph(badge_html, styles["MetaLabel"]))
                lines.append(Spacer(1, 2))

                lines.append(Paragraph(f"<b>Clarification Question:</b> {safe_paragraph_text(c_item.question)}", styles["ClarificationQuestion"]))
                lines.append(Spacer(1, 2))

                lines.append(Paragraph(f"<b>Transcript Context:</b> &ldquo;{safe_paragraph_text(c_item.original_statement)}&rdquo;", styles["ClarificationStatement"]))

                if c_item.explanation:
                    lines.append(Paragraph(f"<b>Rationale:</b> {safe_paragraph_text(c_item.explanation)}", styles["ClarificationStatement"]))

                answer_val = answers_map.get(c_item.id)
                if answer_val:
                    lines.append(Spacer(1, 2))
                    lines.append(Paragraph(f"<b>Resolution Provided:</b> <font color='#047857'><b>[RESOLVED]</b> {safe_paragraph_text(answer_val)}</font>", styles["ClarificationAnswer"]))

                card_table = Table([[lines]], colWidths=[532])
                card_table.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, -1), bg_box_color),
                    ("BOX", (0, 0), (-1, -1), 0.75, border_color),
                    ("TOPPADDING", (0, 0), (-1, -1), 6),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                    ("LEFTPADDING", (0, 0), (-1, -1), 10),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ]))

                story.append(KeepTogether(card_table))
                story.append(Spacer(1, 5))

        # 6.2 Render Open Follow-ups / Deferred Items (if any)
        if has_follow_ups:
            for fu_idx, fu_item in enumerate(open_follow_ups):
                lines = [
                    Paragraph("<b>[OPEN FOLLOW-UP / DEFERRED]</b>  &bull;  <font color='#4F46E5'><b>PENDING FUTURE DISCUSSION</b></font>", styles["MetaLabel"]),
                    Spacer(1, 2),
                    Paragraph(f"<b>Item / Deliverable:</b> {safe_paragraph_text(fu_item)}", styles["ClarificationQuestion"]),
                    Spacer(1, 2),
                    Paragraph("<b>Clarification Required Now:</b> <font color='#4F46E5'>No</font> &mdash; Explicitly deferred in transcript to be determined in the next meeting or future discussion.", styles["ClarificationStatement"]),
                ]

                card_table = Table([[lines]], colWidths=[532])
                card_table.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EEF2FF")),
                    ("BOX", (0, 0), (-1, -1), 0.75, colors.HexColor("#C7D2FE")),
                    ("TOPPADDING", (0, 0), (-1, -1), 6),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                    ("LEFTPADDING", (0, 0), (-1, -1), 10),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ]))

                story.append(KeepTogether(card_table))
                story.append(Spacer(1, 5))

        # 6.3 Audit Summary Banner
        if unresolved_count > 0 and follow_up_count > 0:
            banner_html = (
                f"<font color='#B45309'><b>&bull; Clarification Required &amp; Open Follow-ups:</b></font> "
                f"<b>{unresolved_count}</b> question(s) require participant response. "
                f"In addition, <b>{follow_up_count}</b> item(s) are recorded as open follow-ups deferred to a future meeting."
            )
            bg_banner, border_banner = colors.HexColor("#FFFBEB"), colors.HexColor("#FDE68A")
        elif unresolved_count > 0:
            banner_html = (
                f"<font color='#B45309'><b>&bull; Clarification Required:</b></font> "
                f"<b>{unresolved_count}</b> ambiguity question(s) require participant clarification."
            )
            bg_banner, border_banner = colors.HexColor("#FFFBEB"), colors.HexColor("#FDE68A")
        elif follow_up_count > 0:
            banner_html = (
                f"<font color='#4F46E5'><b>&bull; 0 Clarifications Required:</b></font> "
                f"All active deliverables have clear assignments; <b>{follow_up_count}</b> open follow-up(s) deferred to future discussion."
            )
            bg_banner, border_banner = colors.HexColor("#EEF2FF"), colors.HexColor("#C7D2FE")
        else:
            if resolved_clarifs:
                banner_html = (
                    "<font color='#047857'><b>[VERIFIED] Resolved (No Outstanding Issues)</b></font> &mdash; "
                    "All ambiguities were successfully addressed through user clarification."
                )
            else:
                banner_html = (
                    "<font color='#047857'><b>[VERIFIED] No Outstanding Issues</b></font> &mdash; "
                    "All deliverables, timelines, and decisions were articulated with unambiguous context."
                )
            bg_banner, border_banner = colors.HexColor("#F0FDF4"), colors.HexColor("#BBF7D0")

        banner_p = Paragraph(banner_html, styles["ExecutiveSummary"])
        banner_table = Table([[banner_p]], colWidths=[532])
        banner_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), bg_banner),
            ("BOX", (0, 0), (-1, -1), 0.75, border_banner),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ]))
        story.append(banner_table)

        story.append(Spacer(1, 8))

        # =========================================================================
        # 7. Meeting Transcript (Audit Log)
        # =========================================================================
        if transcript and transcript.strip():
            story.append(Paragraph("6. Source Meeting Transcript (Audit Record)", styles["SectionHeading"]))

            # Format transcript lines into multi-row table so ReportLab splits across pages cleanly
            transcript_lines = [l for l in transcript.strip().split("\n") if l.strip()]
            transcript_rows = [
                [Paragraph(safe_paragraph_text(l), styles["TranscriptText"])]
                for l in transcript_lines
            ]

            transcript_box = Table(transcript_rows, colWidths=[532])
            transcript_box.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
                ("BOX", (0, 0), (-1, -1), 0.75, colors.HexColor("#CBD5E1")),
                ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ]))
            story.append(transcript_box)

        # Build document with dynamic NumberedCanvas bound to report title
        canvas_cls = get_numbered_canvas_class(display_title)
        doc.build(story, canvasmaker=canvas_cls)

        return buffer.getvalue()


