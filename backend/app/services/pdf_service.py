    def sanitize_filename(self, title: Optional[str] = None, meeting_id: Optional[str] = None) -> str:
        """
        Produces a safe, alphanumeric filename for browser downloads.
        Prevents path traversal, special characters, and oversized header values.
        """
        if title and title.strip():
            # Remove non-alphanumeric characters, replace whitespace with underscores
            clean_str = re.sub(r"[^\w\s-]", "", title.strip())
            clean_slug = re.sub(r"[\s_-]+", "_", clean_str).strip("_").lower()
            if clean_slug:
                # Truncate to maximum 45 characters for readability and safety
                truncated_slug = clean_slug[:45].rstrip("_")
                return f"meetmind_{truncated_slug}.pdf"

        if meeting_id and meeting_id.strip():
            clean_id = re.sub(r"[^\w-]", "", meeting_id.strip()).lower()
            return f"meetmind_{clean_id}.pdf"

        return "meetmind_meeting_report.pdf"

