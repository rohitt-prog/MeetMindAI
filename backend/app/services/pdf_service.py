def sanitize_plain_text(text: Optional[str]) -> str:
    """
    Sanitizes dynamic text for ReportLab drawString calls.
    Normalizes typographic characters and strips non-printable control characters.
    Does NOT apply XML escaping (canvas.drawString renders raw strings).
    """
    if not text:
        return ""
    replacements = {
        "\u2018": "'",    # left single quote
        "\u2019": "'",    # right single quote
        "\u201c": '"',    # left double quote
        "\u201d": '"',    # right double quote
        "\u2013": "-",    # en dash
        "\u2014": " - ",  # em dash
        "\u2022": "*",    # bullet
        "\u2026": "...",  # ellipsis
        "\u2713": "[v]",  # checkmark
        "\u2714": "[v]",  # heavy checkmark
        "\xa0": " ",      # non-breaking space
    }
    clean = text.strip()
    for target, rep in replacements.items():
        clean = clean.replace(target, rep)
    return clean


def safe_paragraph_text(text: Optional[str]) -> str:
    """
    Sanitizes dynamic text and XML-escapes it for safe inclusion in ReportLab Paragraph markup.
    Prevents XML entity parsing errors and glyph rendering issues.
    """
    clean = sanitize_plain_text(text)
    return xml_escape(clean)


class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that dynamically calculates the total page count and renders:
    1. A subtle running header on pages > 1 with MeetMind AI brand mark and meeting title.
    2. A professional running footer on all pages with page numbers and confidentiality notice.
    """
    doc_title: str = "Meeting Report"

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_and_footer(num_pages)
            super().showPage()
        super().save()

    def draw_header_and_footer(self, total_pages: int):
        self.saveState()

        # Running header on subsequent pages (pages > 1)
        if self._pageNumber > 1:
            clean_title = sanitize_plain_text(getattr(self, "doc_title", None) or "Meeting Report")
            if len(clean_title) > 42:
                clean_title = clean_title[:40].rstrip() + "..."

            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(colors.HexColor("#4F46E5"))  # Indigo 600
            self.drawString(40, 755, "MEETMIND AI")

            self.setFont("Helvetica", 8)
            self.setFillColor(colors.HexColor("#64748B"))  # Slate 500
            self.drawString(104, 755, f"|  {clean_title}")

            self.setFont("Helvetica-Bold", 7.5)
            self.setFillColor(colors.HexColor("#94A3B8"))  # Slate 400
            self.drawRightString(612 - 40, 755, "EXECUTIVE INTELLIGENCE REPORT")

            self.setStrokeColor(colors.HexColor("#E2E8F0"))  # Slate 200
            self.setLineWidth(0.75)
            self.line(40, 747, 612 - 40, 747)

        # Running footer on all pages
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.75)
        self.line(40, 42, 612 - 40, 42)

        self.setFont("Helvetica", 7.5)
        self.setFillColor(colors.HexColor("#64748B"))
        self.drawString(40, 30, "Generated by MeetMind AI  |  Verified Action Items & Executive Intelligence")

        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(612 - 40, 30, page_str)

        self.restoreState()


def get_numbered_canvas_class(report_title: str):
    """
    Returns a NumberedCanvas subclass with the document title bound for running headers.
    """
    class ReportNumberedCanvas(NumberedCanvas):
        pass

    ReportNumberedCanvas.doc_title = report_title
    return ReportNumberedCanvas


